    def _norm(self, path, cwd="/"):
        if not path:
            return cwd
        if not path.startswith("/"):
            path = (cwd.rstrip("/") + "/" + path) if cwd != "/" else "/" + path
        parts = []
        for p in path.split("/"):
            if p in ("", "."):
                continue
            if p == "..":
                if parts:
                    parts.pop()
            else:
                parts.append(p)
        return "/" + "/".join(parts)

    def resolve(self, path, cwd="/"):
        return self._norm(path, cwd)

    def exists(self, path):
        p = self._norm(path)
        return p in self.files or p in self.dirs

    def is_dir(self, path):
        return self._norm(path) in self.dirs

    def is_file(self, path):
        return self._norm(path) in self.files

    def ls(self, path):
        path = self._norm(path)
        if path not in self.dirs:
            return None
        prefix = "/" if path == "/" else path + "/"
        dirs, files = [], []
        for d in self.dirs:
            if d == path or not d.startswith(prefix):
                continue
            rest = d[len(prefix):]
            if "/" not in rest and rest:
                dirs.append(rest)
        for f in self.files:
            if not f.startswith(prefix):
                continue
            rest = f[len(prefix):]
            if "/" not in rest and rest:
                files.append(rest)
        return sorted(dirs), sorted(files)

    def mkdir(self, path):
        self.dirs.add(self._norm(path))

    def touch(self, path, content=""):
        self.files[self._norm(path)] = content

    def read(self, path):
        return self.files.get(self._norm(path))

    def write(self, path, content):
        self.files[self._norm(path)] = content

    def rm(self, path):
        p = self._norm(path)
        if p in self.files:
            del self.files[p]
            return True
        if p in self.dirs:
            r = self.ls(p)
            if r and (r[0] or r[1]):
                return False
            self.dirs.discard(p)
            return True
        return False


