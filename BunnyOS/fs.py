        files = [a for a in args if not a.startswith("-")]
        if not files:
            return ["wc: missing operand"]
        c = self.fs.read(self._res(files[0]))
        if c is None:
            return [f"wc: {files[0]}: No such file"]
        lines = c.splitlines()
        return [f"{len(lines)} {sum(len(l.split()) for l in lines)} {len(c)} {files[0]}"]

