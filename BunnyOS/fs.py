    def prompt(self):
        short = self.cwd
        home = f"/home/{self.user}"
        if short == home:
            short = "~"
        elif short.startswith(home + "/"):
            short = "~" + short[len(home):]
        return f"{self.user}@{self.host}:{short}$"

    def run(self, line):
        line = line.strip()
        self.history.append(line)
        if not line:
            return []
        try:
            return self._pipeline(line)
        except Exception as e:
            return [f"bash: error: {e}"]

    def _pipeline(self, line):
        # split pipe | (вне кавычек)
        parts, buf, q = [], [], None
        for c in line:
            if c in ('"', "'"):
                if q == c:
                    q = None
                elif q is None:
                    q = c
                buf.append(c)
            elif c == "|" and q is None:
                parts.append("".join(buf)); buf = []
            else:
                buf.append(c)
        parts.append("".join(buf))

        stdin = None
        for part in parts:
            tokens = self._tok(part.strip())
            if not tokens:
                continue
            stdin = self._dispatch(tokens[0], tokens[1:], stdin)
        return stdin or []

    def _tok(self, s):
        out, buf, q = [], [], None
        for c in s:
            if c in ('"', "'"):
                if q == c:
                    q = None
                elif q is None:
                    q = c
                else:
                    buf.append(c)
            elif c == " " and q is None:
                if buf:
                    out.append("".join(buf)); buf = []
            else:
                buf.append(c)
        if buf:
            out.append("".join(buf))
        return out

    def _res(self, p):
        return self.fs.resolve(p, self.cwd)

