    def _cat(self, args):
        if not args:
            return ["cat: missing operand"]
        out = []
        for a in args:
            # Реальные /proc/ файлы!
            if a in ("/proc/uptime", "/proc/loadavg", "/proc/version",
                     "/proc/cpuinfo", "/proc/meminfo"):
                try:
                    with open(a) as f:
                        content = f.read()
                    out.extend(content.rstrip("\n").split("\n"))
                    continue
                except Exception:
                    pass
            # Реальный /etc/os-release
            if a == "/etc/os-release":
                import real_sys
                out.extend(real_sys.os_release())
                continue
            if a == "/etc/passwd":
                try:
                    with open(a) as f:
                        out.extend(f.read().rstrip("\n").split("\n"))
                    continue
                except Exception:
                    pass
            # Старая проверка для /proc (уже обработана выше)
            if False:
                try:
                    with open(a) as f:
                        content = f.read()
                    out.extend(content.rstrip("\n").split("\n"))
                    continue
                except Exception:
                    pass
            c = self.fs.read(self._res(a))
            if c is None:
                out.append(f"cat: {a}: No such file")
            else:
                out.extend(c.rstrip("\n").split("\n"))
