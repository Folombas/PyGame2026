"""Музыкальная теория — данные и уровни сложности."""

NOTE_NAMES_EN = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
NOTE_NAMES_RU = ["До", "До#", "Ре", "Ре#", "Ми", "Фа", "Фа#",
                 "Соль", "Соль#", "Ля", "Ля#", "Си"]

INTERVALS = [
    (1, "m2", "Малая секунда", 2),
    (2, "M2", "Большая секунда", 1),
    (3, "m3", "Малая терция", 1),
    (4, "M3", "Большая терция", 1),
    (5, "P4", "Чистая кварта", 1),
    (6, "TT", "Тритон", 3),
    (7, "P5", "Чистая квинта", 1),
    (8, "m6", "Малая секста", 2),
    (9, "M6", "Большая секста", 2),
    (10, "m7", "Малая септима", 2),
    (11, "M7", "Большая септима", 3),
    (12, "P8", "Октава", 1),
]

CHORDS = [
    ("maj", [0, 4, 7], "Мажорное трезвучие", 1),
    ("min", [0, 3, 7], "Минорное трезвучие", 1),
    ("dim", [0, 3, 6], "Уменьшенное трезвучие", 2),
    ("aug", [0, 4, 8], "Увеличенное трезвучие", 3),
    ("maj7", [0, 4, 7, 11], "Большой мажорный септаккорд", 3),
    ("min7", [0, 3, 7, 10], "Малый минорный септаккорд", 3),
    ("dom7", [0, 4, 7, 10], "Доминантсептаккорд", 3),
    ("m7b5", [0, 3, 6, 10], "Полууменьшенный септаккорд", 4),
    ("dim7", [0, 3, 6, 9], "Уменьшенный септаккорд", 4),
]

LEVEL_TITLES = {1: "Новичок", 2: "Ученик", 3: "Продвинутый", 4: "Мастер"}


def midi_to_name(note: int, lang: str = "ru") -> str:
    names = NOTE_NAMES_RU if lang == "ru" else NOTE_NAMES_EN
    octave = (note // 12) - 1
    return f"{names[note % 12]}{octave}"


def intervals_for_level(level: int):
    return [i for i in INTERVALS if i[3] <= level]


def chords_for_level(level: int):
    return [c for c in CHORDS if c[3] <= level]


def note_pool(level: int):
    if level == 1:
        return [0, 2, 4, 5, 7, 9, 11]
    return list(range(12))
